"""Describe the NASA POWER cells that are used as extra data points in the app (decision D15): writes models/cells.yaml.

A cell is used when it is not already covered by one of the named sites, it is not outside the Delta region (latitude 30.0 to 31.0), and its mean height is
below 200 m. Each cell gets a plain name from its coordinates (no place is asserted), and a caveat:
  sea          mean daily maximum below 25 C: the cell is mostly Mediterranean sea, heat numbers are not reliable (same rule as Damietta);
  desert_edge  mean height 60 m or more: the cell is mostly desert plateau, farmland along the Nile is greener and cooler at night than the cell suggests.
Cell files come from src/fieldshift/ingest/fetch_power_cells.py (data/raw/power_cells/, gitignored).
Run: .venv/Scripts/python scripts/build_cells.py
"""
import json
import pathlib

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
AR = str.maketrans("0123456789.", "٠١٢٣٤٥٦٧٨٩٫")


def cell_of(lat, lon):
    return round((lat + 90) / 0.5), round((lon + 180) / 0.625)


def main():
    sites = yaml.safe_load((ROOT / "models" / "sites.yaml").read_text(encoding="utf8"))["sites"]
    named = {cell_of(s["lat"], s["lon"]) for s in sites.values()}
    out = {}
    for f in sorted((ROOT / "data" / "raw" / "power_cells").glob("cell_*_daily.json")):
        j = json.loads(f.read_text())
        lon, lat, z = j["geometry"]["coordinates"]
        if cell_of(lat, lon) in named or not (30.0 <= lat <= 31.0) or z >= 200:
            continue
        tx = [v for v in j["properties"]["parameter"]["T2M_MAX"].values() if v > -900]
        tmax = sum(tx) / len(tx)
        kind = "sea" if tmax < 25 else ("desert_edge" if z >= 60 else None)
        key = f.name.replace("_daily.json", "")
        c = {"name_en": f"NASA data cell {lat}°N {lon}°E", "name_ar": f"خلية بيانات ناسا {str(lat).translate(AR)} شمالاً {str(lon).translate(AR)} شرقاً",
             "lat": lat, "lon": lon, "elevation_m": round(z), "tmax_mean_c": round(tmax, 1), "kind": "cell"}
        if kind == "sea":
            c["caveat_kind"] = "sea"
            c["weather_caveat"] = "NASA POWER cell is mostly sea (mean daily maximum below 25 C). Do not use for heat claims or show as low risk."
        elif kind == "desert_edge":
            c["caveat_kind"] = "desert_edge"
            c["weather_caveat"] = f"This NASA cell is mostly desert plateau (average height about {round(z)} m). Farmland along the Nile is usually greener and cooler at night than the cell suggests, so treat the numbers as rough."
        out[key] = c
    header = "# Extra NASA POWER data points (one per ~50 km cell), generated by scripts/build_cells.py. Do not edit by hand.\n"
    (ROOT / "models" / "cells.yaml").write_text(header + yaml.safe_dump({"cells": out}, allow_unicode=True, sort_keys=True), encoding="utf8")
    print(len(out), "cells:", ", ".join(f"{k.replace('cell_', '')}({v.get('caveat_kind') or 'ok'})" for k, v in out.items()))


if __name__ == "__main__":
    main()
